package com.privacyshield.proxy

import android.app.Notification
import android.app.NotificationChannel
import android.app.NotificationManager
import android.app.PendingIntent
import android.content.Intent
import android.net.VpnService
import android.os.Build
import android.os.ParcelFileDescriptor
import androidx.core.app.NotificationCompat
import com.privacyshield.proxy.core.ForegroundStarts
import com.privacyshield.proxy.core.MihomoCore
import com.privacyshield.proxy.core.RoutingConfig
import java.io.File

/**
 * Captures device traffic into a TUN and hands it to the Mihomo (Clash.Meta)
 * engine, which applies the rule map (per-app -> node, domain/ip/geo rules)
 * generated by RoutingConfig. Whole-device capture is used so Mihomo's rules
 * fully control routing; unmatched traffic hits the final MATCH,<finalTarget>.
 */
class ShieldVpnService : VpnService() {

    private val watchdog = android.os.Handler(android.os.Looper.getMainLooper())
    private var engineThread: android.os.HandlerThread? = null
    private var engine: android.os.Handler? = null
    private var tun: ParcelFileDescriptor? = null

    override fun onCreate() {
        super.onCreate()
        // Cold start of this process is what the foreground-service timer measures.
        // Nothing else may run first: the emulator images have no KVM, and the
        // main thread was still inside startTunnel when Android gave up on startup.
        ForegroundStarts.start(this, NOTIF_ID, startingNotification(), ForegroundStarts.SPECIAL_USE)
        val thread = android.os.HandlerThread("shield-vpn")
        thread.start()
        engineThread = thread
        engine = android.os.Handler(thread.looper)
    }

    companion object {
        const val ACTION_START = "com.privacyshield.proxy.START"
        const val ACTION_STOP = "com.privacyshield.proxy.STOP"
        private const val CHANNEL_ID = "shieldproxy_vpn"
        private const val NOTIF_ID = 1
        private const val WATCHDOG_MS = 20_000L

        @Volatile
        var running: Boolean = false
            private set

        /** True between an explicit Start and an explicit Stop. Used to auto-revive
         *  the engine if Android/Samsung kills it without the user asking. */
        @Volatile
        var wantRunning: Boolean = false
            private set

        /**
         * Cross-process "is the engine running?" — the service now lives in a separate ":vpn"
         * process (so a native engine crash can't kill the UI), which means the `running` static
         * above is NOT visible from the UI process. Ask ActivityManager instead (it reports our
         * own app's services across all processes).
         */
        fun isRunning(ctx: android.content.Context): Boolean {
            return try {
                val am = ctx.getSystemService(android.content.Context.ACTIVITY_SERVICE) as android.app.ActivityManager
                @Suppress("DEPRECATION")
                am.getRunningServices(Int.MAX_VALUE).any {
                    it.service.className == ShieldVpnService::class.java.name
                }
            } catch (_: Exception) {
                false
            }
        }
    }

    override fun onStartCommand(intent: Intent?, flags: Int, startId: Int): Int {
        // startForegroundService() crashes if this returns before startForeground(),
        // and loading Mihomo can take longer than that window on a cold emulator.
        ForegroundStarts.start(this, NOTIF_ID, startingNotification(), ForegroundStarts.SPECIAL_USE)
        val action = intent?.action
        if (action == ACTION_STOP) wantRunning = false else wantRunning = true
        val handler = engine
        if (handler == null) {
            stopSelf()
            return START_NOT_STICKY
        }
        handler.post {
            // A newer start may already have set wantRunning. Do not tear the
            // tunnel down, and do not let onDestroy quit the thread under it.
            if (!wantRunning) {
                stopTunnel()
                return@post
            }
            // ACTION_START, or a START_STICKY restart after the process was killed
            // (intent == null) — in that case revive from the persisted active profile.
            startTunnel()
            scheduleWatchdog()
        }
        return if (action == ACTION_STOP) START_NOT_STICKY else START_STICKY
    }

    /** Periodically ensure the engine is actually alive; revive it if it died
     *  while the user still wants it running. */
    private fun scheduleWatchdog() {
        watchdog.removeCallbacksAndMessages(null)
        watchdog.postDelayed(object : Runnable {
            override fun run() {
                if (!wantRunning) return
                if (!MihomoCore.running) {
                    // engine died on its own — rebuild the tunnel + restart Mihomo
                    engine?.post {
                        if (!wantRunning) return@post
                        stopEngineOnly()
                        startTunnel()
                    }
                }
                watchdog.postDelayed(this, WATCHDOG_MS)
            }
        }, WATCHDOG_MS)
    }

    private fun markEngineReady(token: String?) {
        val marker = File(filesDir, "engine_ready.txt")
        if (token == null) marker.delete() else marker.writeText(token)
    }

    private fun startTunnel() {
        // Drop any stale marker before the new tun exists, so a waiter cannot
        // treat the previous session as ready.
        markEngineReady(null)
        // Switching lists: if already running, tear the engine down first and
        // re-establish with the newly-activated profile's config.
        if (running) stopEngineOnly()
        val cfg = try {
            val active = RoutingConfig.load(this)
            val saved = runCatching { com.privacyshield.proxy.core.ProfileStore.load(this) }
                .getOrDefault(emptyList())
            com.privacyshield.proxy.core.EngineRoutes.merge(active, saved.map { it.config })
        } catch (e: Exception) {
            lastError = "Protected routing data could not be unlocked"
            stopSelf()
            return
        }

        val androidUser = com.privacyshield.proxy.core.AndroidProfile.current(this)
        val builder = Builder()
            .setSession(com.privacyshield.proxy.core.AndroidProfile.vpnSessionName(
                androidUser.userId, androidUser.managed))
            .setMtu(9000)
            .addAddress("172.19.0.1", 30)
            .addRoute("0.0.0.0", 0)
            .addDnsServer("172.19.0.2")
            // Always capture IPv6. Omitting ::/0 does not disable IPv6; it lets IPv6-capable
            // apps bypass an IPv4-only VPN through the underlying Nigerian network. When the
            // profile has ipv6=false, Mihomo suppresses AAAA and rejects captured IPv6 safely.
            .addAddress("fdfe:dcba:9876::1", 126)
            .addRoute("::", 0)

        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.LOLLIPOP_MR1) {
            builder.setBlocking(false)
        }

        // addDisallowedApplication is resolved in this Android user only. The other
        // profile's copy of a package has a different UID and is not affected.
        try {
            builder.addDisallowedApplication(packageName)
        } catch (_: Exception) {
        }

        // Clone routes are enforced inside this tunnel. The hook dials 127.0.0.1:<port>, which
        // never enters the TUN. Everything else from the container UID is captured and rejected
        // by the UID rule, so a missed socket cannot use the phone network.
        // When no clone route is configured, leave the containers excluded so Blackbox's own
        // UI traffic is not rewritten by fake-ip.
        if (cfg.bbMap.isEmpty()) {
            for (container in com.privacyshield.proxy.core.CloneListeners.CONTAINER_PACKAGES) {
                try { builder.addDisallowedApplication(container) } catch (_: Exception) {}
            }
        }

        val pfd = try {
            builder.establish()
        } catch (e: Exception) {
            stopSelf(); return
        }
        if (pfd == null) {
            stopSelf(); return
        }
        // Mihomo closes the fd it is given. A second owner stays here so stop
        // can drop tun0 without closing Mihomo's fd (API 30+ fdsan aborts on
        // a double-close of the same descriptor).
        tun?.close()
        tun = pfd
        val tunFd = pfd.dup().detachFd()

        // Mihomo home dir holds config.yaml + downloaded geo/provider files.
        val home = File(filesDir, "mihomo").apply { mkdirs() }
        // Remove any legacy plaintext config left by older builds.
        File(home, "config.yaml").delete()
        val runtimeDir = File(cacheDir, "mihomo-runtime").apply { mkdirs() }
        val configFile = File(runtimeDir, "config.yaml")
        val pm = packageManager
        val uidResolver: (String) -> Int? = { pkg ->
            try {
                val uid = pm.getPackageUid(pkg, com.privacyshield.proxy.core.PackageQuery.FLAGS)
                if (com.privacyshield.proxy.core.PackageQuery.sameUser(uid, androidUser.userId)) uid else null
            } catch (_: Exception) {
                null
            }
        }
        // Resolve proxy-server hostnames to an IP now, on the underlying network
        // (our app is excluded from the VPN), so Mihomo never needs in-tunnel DNS
        // to reach the proxy. Target domains are still resolved remotely by the
        // proxy via fake-ip.
        val serverResolver: (String) -> String? = { host ->
            if (host.matches(Regex("^[0-9.]+$")) || host.contains(":")) {
                host // already an IP literal
            } else {
                try {
                    java.net.InetAddress.getByName(host).hostAddress
                } catch (_: Exception) {
                    null
                }
            }
        }
        configFile.writeText(cfg.toClashYaml(tunFd, uidResolver, serverResolver))

        ForegroundStarts.start(this, NOTIF_ID, buildNotification(cfg), ForegroundStarts.SPECIAL_USE)

        // Protect Mihomo's outbound sockets so proxy connections exit the real
        // network instead of looping back into our own tun.
        val self = this
        MihomoCore.setProtector(object : mobilebridge.Protector {
            override fun protect(fd: Long): Boolean = self.protect(fd.toInt())
        })

        // Per-app routing: resolve each connection's owning app uid via the
        // official getConnectionOwnerUid API (works because we are the active
        // VPN app), so UID/PROCESS rules match on non-rooted Android.
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
            val cm = getSystemService(android.net.ConnectivityManager::class.java)
            MihomoCore.setUidResolver(object : mobilebridge.UidQuery {
                override fun query(
                    protocol: Long, srcIp: String, srcPort: Long, destIp: String, destPort: Long
                ): Long {
                    return try {
                        val local = java.net.InetSocketAddress(
                            java.net.InetAddress.getByName(srcIp), srcPort.toInt()
                        )
                        val remote = java.net.InetSocketAddress(
                            java.net.InetAddress.getByName(destIp), destPort.toInt()
                        )
                        cm.getConnectionOwnerUid(protocol.toInt(), local, remote).toLong()
                    } catch (e: Exception) {
                        -1L
                    }
                }
            })
        }

        val err = MihomoCore.start(home.absolutePath, configFile.absolutePath)
        // Mihomo has loaded the configuration; do not retain credentials in a plaintext file.
        runCatching { configFile.delete() }
        if (err.isNotEmpty()) {
            lastError = err
            stopTunnel()
            return
        }
        running = true
        val readyPort = cfg.nodes.firstOrNull { it.name == "emu" }?.port
            ?: cfg.nodes.firstOrNull { it.isValid() }?.port
        markEngineReady(readyPort?.toString() ?: "up")
    }

    /** Stop the engine + close the tun, but keep the service/foreground alive
     *  (used when switching to another profile). */
    private fun stopEngineOnly() {
        // Close our fd before Mihomo.stop(). Stop waits for the last tun owner,
        // and holding this dup across that call left tun0 up for the whole wait.
        val owned = tun
        tun = null
        try {
            owned?.close()
        } catch (_: Exception) {
        }
        if (running || MihomoCore.running) {
            MihomoCore.stop()
            running = false
        }
        markEngineReady(null)
    }

    private fun stopTunnel() {
        watchdog.removeCallbacksAndMessages(null)
        stopEngineOnly()
        stopForeground(STOP_FOREGROUND_REMOVE)
        stopSelf()
    }

    override fun onDestroy() {
        // If the system is killing us but the user still wants routing, DON'T flip
        // wantRunning — START_STICKY will restart us and the watchdog revives the engine.
        // Quitting the engine thread here raced a restart: the next stop was posted
        // to a dead thread and tun0 stayed up.
        watchdog.removeCallbacksAndMessages(null)
        if (!wantRunning) {
            val thread = engineThread
            engine?.post {
                if (!wantRunning) {
                    stopEngineOnly()
                    thread?.quit()
                }
            }
        }
        super.onDestroy()
    }

    override fun onRevoke() {
        // User revoked VPN consent (or another VPN took over) — stop for real.
        wantRunning = false
        engine?.post { stopTunnel() }
        super.onRevoke()
    }

    private fun startingNotification(): Notification {
        val nm = getSystemService(NotificationManager::class.java)
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
            nm.createNotificationChannel(
                NotificationChannel(CHANNEL_ID, "ShieldProxy", NotificationManager.IMPORTANCE_LOW)
            )
        }
        return NotificationCompat.Builder(this, CHANNEL_ID)
            .setContentTitle("Starting route")
            .setSmallIcon(R.drawable.ic_shield)
            .setOngoing(true)
            .build()
    }

    private fun buildNotification(cfg: RoutingConfig): Notification {
        val nm = getSystemService(NotificationManager::class.java)
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
            nm.createNotificationChannel(
                NotificationChannel(CHANNEL_ID, "ShieldProxy", NotificationManager.IMPORTANCE_LOW)
            )
        }
        val open = PendingIntent.getActivity(
            this, 0, Intent(this, MainActivity::class.java), PendingIntent.FLAG_IMMUTABLE
        )
        val nodes = cfg.nodes.count { it.isValid() }
        val mapped = cfg.appMap.size
        return NotificationCompat.Builder(this, CHANNEL_ID)
            .setContentTitle("Routing active")
            .setContentText("$nodes nodes · $mapped apps mapped · ${cfg.processMatchMode.clash}")
            .setSmallIcon(R.drawable.ic_shield)
            .setOngoing(true)
            .setContentIntent(open)
            .build()
    }
}

/** Last engine error, surfaced to the UI. */
@Volatile
var lastError: String = ""
